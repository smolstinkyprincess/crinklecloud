#!/data/data/com.termux/files/usr/bin/bash
# Installs RazrGuard's runit services into Termux. Run inside Termux on the phone:
#   bash install-services.sh
# Idempotent: re-run after editing services.conf. New services are created DISABLED
# (a `down` file) so they don't fight any instance you still start by hand; enable each
# with `sv-enable NAME` once the old one is stopped.

set -euo pipefail

SVDIR_FROM_ENV="${SVDIR:-}"
HERE="$(cd "$(dirname "$0")" && pwd)"
CONF="$HERE/services.conf"
SVDIR="$PREFIX/var/service"
LOGDIR="$PREFIX/var/log/sv"
BOOT="$HOME/.termux/boot/start-services.sh"

command -v runsv >/dev/null || pkg install -y termux-services
mkdir -p "$SVDIR" "$LOGDIR"

write() { # path mode < content; only touches the file if content changed (flash wear)
    local tmp
    tmp="$(mktemp)"
    cat >"$tmp"
    if cmp -s "$tmp" "$1"; then rm -f "$tmp"; else mv "$tmp" "$1"; fi
    chmod "$2" "$1"
}

new=()
while read -r name where cmd; do
    [[ -z "$name" || "$name" == \#* ]] && continue
    dir="$SVDIR/$name"
    [[ -d "$dir" ]] || { mkdir -p "$dir"; touch "$dir/down"; new+=("$name"); }
    mkdir -p "$dir/log" "$dir/control" "$LOGDIR/$name"

    printf '%s\n' "$cmd" | write "$dir/cmd" 644

    case "$where" in
        host)
            launch='eval "exec $CMD"' ;;
        proot)
            launch='exec proot-distro login debian -- /bin/sh -c "exec $CMD"' ;;
        proot:*)
            launch="exec proot-distro login debian --user ${where#proot:} -- /bin/sh -c \"exec \$CMD\"" ;;
        *)
            echo "[!] $name: unknown location '$where', skipping" >&2; continue ;;
    esac

    write "$dir/run" 755 <<EOF
#!/data/data/com.termux/files/usr/bin/sh
# Generated by RazrGuard install-services.sh from services.conf; edits will be overwritten.
exec 2>&1
CMD=\$(cat ./cmd)
$launch
EOF

    # Crash-loop backoff: runsv restarts instantly, which burns CPU and log writes.
    # \$1 is the exit code (-1 if killed by a signal), \$2 the signal.
    write "$dir/finish" 755 <<'EOF'
#!/data/data/com.termux/files/usr/bin/sh
[ "$1" = 0 ] || [ "$2" = 15 ] || sleep 15
EOF

    if [[ "$where" == proot* ]]; then
        # Graceful stop for proot services: TERM the real service process inside proot
        # instead of proot itself (killing proot SIGKILLs everything it traces, which is
        # not kind to Vaultwarden's or Jellyfin's databases). Exit 0 tells runsv not to
        # send its own TERM; proot exits on its own once the command does.
        write "$dir/control/t" 755 <<'EOF'
#!/data/data/com.termux/files/usr/bin/sh
# Walk down from the run process to proot, then signal proot's direct children
# (the service itself, not its own helpers like ffmpeg).
targets() {
    if [ "$(cat "/proc/$1/comm" 2>/dev/null)" = proot ]; then
        pgrep -P "$1"
    else
        for k in $(pgrep -P "$1"); do targets "$k"; done
    fi
}
pid=$(cat ./supervise/pid 2>/dev/null)
[ -n "$pid" ] || exit 1
t=$(targets "$pid")
# Nothing found: exit non-zero so runsv falls back to its own TERM
[ -n "$t" ] || exit 1
kill -TERM $t
EOF
    else
        rm -f "$dir/control/t"
    fi

    write "$dir/log/run" 755 <<EOF
#!/data/data/com.termux/files/usr/bin/sh
exec svlogd -tt "$LOGDIR/$name"
EOF
    # At most 3 x 1 MB per service
    printf 's1000000\nn3\n' | write "$LOGDIR/$name/config" 644
done <"$CONF"

# sshd ships with its own service in the openssh package
[[ -d "$SVDIR/sshd" ]] && rm -f "$SVDIR/sshd/down"

# Boot/recovery entrypoint (Termux:Boot runs it; GuardService re-runs it on failure)
mkdir -p "$(dirname "$BOOT")"
# Backups go outside boot/: Termux:Boot runs every file in that directory
backup() {
    if [[ -f "$1" ]] && ! grep -q 'RazrGuard install-services.sh' "$1"; then
        cp "$1" "$2"
        echo "[*] Old $(basename "$1") backed up to $2"
    fi
}
backup "$BOOT" "$HOME/.termux/start-services.sh.pre-runit"
write "$BOOT" 755 <"$HERE/start-services.sh"
backup "$HOME/.termux/start-shizuku.sh" "$HOME/.termux/start-shizuku.sh.pre-runit"
write "$HOME/.termux/start-shizuku.sh" 755 <"$HERE/start-shizuku.sh"
write "$HOME/.termux/tune-storage.sh" 755 <"$HERE/tune-storage.sh"
write "$HOME/.termux/razrguard-monitor.sh" 755 <"$HERE/razrguard-monitor.sh"
mkdir -p "$HOME/.config/razrguard"
[[ -f "$HOME/.config/razrguard/monitor.conf" ]] || \
    install -m 600 "$HERE/monitor.conf.example" "$HOME/.config/razrguard/monitor.conf"
backup "$HOME/restart-services.sh" "$HOME/restart-services.sh.pre-runit"
write "$HOME/restart-services.sh" 755 <"$HERE/restart-services.sh"

pgrep -x runsvdir >/dev/null || SVDIR="$SVDIR" LOGDIR="$PREFIX/var/log" service-daemon start

echo "[+] Services installed in $SVDIR (supervisor running)"
if ((${#new[@]})); then
    echo "[*] New services are disabled until you stop any manual instance and run:"
    printf '      sv-enable %s\n' "${new[@]}"
fi
if [[ "${SVDIR_FROM_ENV:-}" != "$SVDIR" ]]; then
    echo "[!] sv/sv-enable need SVDIR in your shell. Open a new Termux session, or run:"
    echo "      export SVDIR=$SVDIR"
fi
